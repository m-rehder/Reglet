#!/usr/bin/env python3
"""Generates Reglet.Core/BidiData.cs from the UCD files (the tool is not shipped)."""
import re
import sys

MAX = 0x10FFFF
CLASSES = {
    "Left_To_Right": 0, "Right_To_Left": 1, "Arabic_Letter": 2, "European_Number": 3,
    "European_Separator": 4, "European_Terminator": 5, "Arabic_Number": 6,
    "Common_Separator": 7, "Nonspacing_Mark": 8, "Boundary_Neutral": 9,
    "Paragraph_Separator": 10, "Segment_Separator": 11, "White_Space": 12,
    "Other_Neutral": 13, "Left_To_Right_Embedding": 14, "Right_To_Left_Embedding": 15,
    "Left_To_Right_Override": 16, "Right_To_Left_Override": 17,
    "Pop_Directional_Format": 18, "Left_To_Right_Isolate": 19,
    "Right_To_Left_Isolate": 20, "First_Strong_Isolate": 21,
    "Pop_Directional_Isolate": 22,
}
NAMES = {v: k for k, v in CLASSES.items()}
ABBREV = {name: value for name, value in zip(
    ["L", "R", "AL", "EN", "ES", "ET", "AN", "CS", "NSM", "BN", "B", "S", "WS",
     "ON", "LRE", "RLE", "LRO", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI"],
    range(23))}


def class_value(name):
    return ABBREV[name] if name in ABBREV else CLASSES[name]

def parse_range(text):
    if ".." in text:
        a, b = text.split("..")
        return int(a, 16), int(b, 16)
    v = int(text, 16)
    return v, v

def main(derived_path, brackets_path, mirroring_path, version, out_path):
    table = bytearray(MAX + 1)  # default 0 = L
    missing = []
    for line in open(derived_path, encoding="utf-8"):
        if line.startswith("# @missing:"):
            body = line[len("# @missing:"):].split("#")[0]
            rng, cls = [p.strip() for p in body.split(";")]
            missing.append((*parse_range(rng), class_value(cls)))
    for start, end, cls in missing:
        for cp in range(start, end + 1):
            table[cp] = cls
    for line in open(derived_path, encoding="utf-8"):
        line = line.split("#")[0].strip()
        if not line:
            continue
        rng, cls = [p.strip() for p in line.split(";")]
        start, end = parse_range(rng)
        value = class_value(cls)
        for cp in range(start, end + 1):
            table[cp] = value

    ranges = []
    start = 0
    current = table[0]
    for cp in range(1, MAX + 1):
        if table[cp] != current:
            if current != 0:
                ranges.append((start, cp - 1, current))
            start = cp
            current = table[cp]
    if current != 0:
        ranges.append((start, MAX, current))

    brackets = []
    for line in open(brackets_path, encoding="utf-8"):
        line = line.split("#")[0].strip()
        if not line:
            continue
        cp, paired, kind = [p.strip() for p in line.split(";")]
        brackets.append((int(cp, 16), int(paired, 16), 1 if kind == "o" else 0))
    brackets.sort()

    # BidiMirroring.txt: the glyph a character takes at an odd (right-to-left) level (rule L4).
    mirrors = []
    for line in open(mirroring_path, encoding="utf-8"):
        line = line.split("#")[0].strip()
        if not line:
            continue
        cp, mirror = [p.strip() for p in line.split(";")]
        mirrors.append((int(cp, 16), int(mirror, 16)))
    mirrors.sort()

    with open(out_path, "w", encoding="utf-8") as out:
        out.write("// <auto-generated>\n")
        out.write(f"// Unicode bidi classes (UAX #9) from DerivedBidiClass.txt, BidiBrackets.txt and BidiMirroring.txt, Unicode {version}.\n")
        out.write("// Generated with tools/generate-bidi-data.py; do not edit by hand.\n")
        out.write("// </auto-generated>\n\n")
        out.write("namespace Reglet;\n\n")
        out.write("internal static partial class BidiData\n{\n")
        out.write(f"    // {len(ranges)} Bereiche (Standard L ausgelassen), {len(brackets)} Klammerpaare, {len(mirrors)} Spiegelzeichen.\n")
        out.write("    private static readonly (int Start, int End, byte Class)[] Ranges =\n    [\n")
        for start, end, cls in ranges:
            out.write(f"        (0x{start:04X}, 0x{end:04X}, {cls}), // {NAMES[cls]}\n")
        out.write("    ];\n\n")
        out.write("    private static readonly (int Code, int Paired, bool Open)[] Brackets =\n    [\n")
        for cp, paired, kind in brackets:
            out.write(f"        (0x{cp:04X}, 0x{paired:04X}, {'true' if kind else 'false'}),\n")
        out.write("    ];\n\n")
        out.write("    private static readonly (int Code, int Mirror)[] Mirrors =\n    [\n")
        for cp, mirror in mirrors:
            out.write(f"        (0x{cp:04X}, 0x{mirror:04X}),\n")
        out.write("    ];\n}\n")
    print(f"ranges={len(ranges)} brackets={len(brackets)} mirrors={len(mirrors)}")

if __name__ == "__main__":
    # generate-bidi-data.py DerivedBidiClass.txt BidiBrackets.txt BidiMirroring.txt 18.0.0 BidiData.cs
    main(sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4], sys.argv[5])
