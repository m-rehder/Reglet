namespace Reglet;

/// <summary>Supported media type of an image.</summary>
public enum ImageMediaType
{
    /// <summary>Portable Network Graphics (PNG).</summary>
    Png,

    /// <summary>JPEG.</summary>
    Jpeg,

    /// <summary>Scalable Vector Graphics (SVG). Supported by ODT; DOCX and PDF report it.</summary>
    Svg,
}
