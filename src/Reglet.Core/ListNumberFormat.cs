namespace Reglet;

/// <summary>Number format of a numbered list.</summary>
public enum ListNumberFormat
{
    /// <summary>Arabic numerals: 1, 2, 3.</summary>
    Decimal,

    /// <summary>Lowercase Roman numerals: i, ii, iii.</summary>
    LowerRoman,

    /// <summary>Uppercase Roman numerals: I, II, III.</summary>
    UpperRoman,

    /// <summary>Lowercase letters: a, b, c.</summary>
    LowerLetter,

    /// <summary>Uppercase letters: A, B, C.</summary>
    UpperLetter,
}
